import assert from "node:assert/strict";
import { chromium } from "playwright";

const base = process.env.NAVIGATION_TEST_URL ?? "http://127.0.0.1:3013";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(base).hostname), "Navigation checks require a local frontend.");
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/*.supabase.co/**", (route) => { errors.push("Refused hosted request"); return route.abort(); });
  const response = await page.goto(base + "/");
  assert.equal(response.status(), 200);
  const navigation = page.getByRole("navigation", { name: "Main navigation", exact: true });
  const about = navigation.getByRole("link", { name: "About", exact: true });
  const overview = navigation.getByRole("link", { name: "Overview", exact: true });
  await about.focus();
  await overview.waitFor();
  await about.press("ArrowDown");
  assert.ok(await overview.evaluate((element) => element === document.activeElement), "ArrowDown moves focus into About sections");
  await overview.press("Escape");
  assert.equal(await about.getAttribute("aria-expanded"), "false");
  assert.ok(await about.evaluate((element) => element === document.activeElement));
  const more = navigation.getByRole("button", { name: "More", exact: true });
  await more.click();
  const store = navigation.getByRole("link", { name: "Store", exact: true });
  await store.waitFor();
  await more.press("ArrowDown");
  assert.ok(await store.evaluate((element) => element === document.activeElement), "ArrowDown moves focus into More links");
  await store.press("Escape");
  assert.equal(await more.getAttribute("aria-expanded"), "false");
  await page.keyboard.press("Tab");
  await page.screenshot({ path: "/private/tmp/velocity-home-desktop.png", fullPage: true, animations: "disabled" });

  const themes = page.getByRole("radiogroup", { name: "Theme preference", exact: true });
  await themes.getByRole("radio", { name: "Use dark color theme", exact: true }).check();
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  await page.screenshot({ path: "/private/tmp/velocity-home-dark.png", fullPage: true, animations: "disabled" });
  await themes.getByRole("radio", { name: "Use light color theme", exact: true }).check();
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light");
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
  await page.setViewportSize({ width: 390, height: 844 });
  const open = page.getByRole("button", { name: "Open navigation", exact: true });
  await open.click();
  const close = page.getByRole("button", { name: "Close navigation", exact: true });
  await close.waitFor();
  assert.ok(await navigation.getByRole("link", { name: "Tools", exact: true }).isVisible());
  await navigation.getByRole("button", { name: "About sections", exact: true }).click();
  await overview.waitFor();
  await overview.press("Escape");
  assert.equal(await navigation.getByRole("button", { name: "About sections", exact: true }).getAttribute("aria-expanded"), "false");
  await close.press("Escape");
  await open.waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "Homepage fits the mobile viewport");
  await page.screenshot({ path: "/private/tmp/velocity-home-mobile.png", fullPage: true, animations: "disabled" });
  await open.click();
  await navigation.getByRole("link", { name: "Tools", exact: true }).click();
  await page.waitForURL(base + "/login");
  await page.getByRole("heading", { name: "Sign In to Portal", exact: true }).waitFor();
  assert.equal(await page.getByRole("link", { name: "Sign in", exact: true }).count(), 0, "Login does not repeat the account pill");
  const google = page.getByRole("button", { name: "Sign in with Google", exact: true });
  await google.waitFor();
  assert.equal(await google.locator("svg").count(), 1, "Configured Google sign-in shows its icon");
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "Login fits the mobile viewport");
  await page.screenshot({ path: "/private/tmp/velocity-login-mobile.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "/private/tmp/velocity-login-desktop.png", fullPage: true, animations: "disabled" });

  await page.goto(base + "/privacy");
  await page.getByRole("heading", { name: "Privacy Policy", exact: true }).waitFor();
  const privacyThemes = page.getByRole("radiogroup", { name: "Theme preference", exact: true });
  await privacyThemes.getByRole("radio", { name: "Use dark color theme", exact: true }).check();
  const darkBackground = await page.getByRole("main").evaluate((element) => getComputedStyle(element).backgroundColor);
  await page.screenshot({ path: "/private/tmp/velocity-privacy-dark.png", fullPage: true, animations: "disabled" });
  await privacyThemes.getByRole("radio", { name: "Use light color theme", exact: true }).check();
  const lightBackground = await page.getByRole("main").evaluate((element) => getComputedStyle(element).backgroundColor);
  assert.notEqual(darkBackground, lightBackground, "Privacy page uses theme-aware background tokens");
  await page.screenshot({ path: "/private/tmp/velocity-privacy-light.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "Privacy page fits the mobile viewport");
  assert.deepEqual(errors, []);
  console.log("Homepage, desktop/mobile header disclosures, keyboard focus, themes, Tools navigation, login presentation and privacy page passed.");
} finally {
  await browser.close();
}
