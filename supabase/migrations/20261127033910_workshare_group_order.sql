-- One canonical display order for all registration-group consumers.
-- Identity allocation also covers older clients and account-import triggers:
-- every newly created group is appended without computing max()+1 in clients.
alter table public.workshare_groups add column sort_order integer generated by default as identity;
update public.workshare_groups set sort_order = 0 where id = 'unassigned';
with positions as (
  select id, row_number() over (order by name, id)::integer as position
  from public.workshare_groups where id <> 'unassigned'
)
update public.workshare_groups g set sort_order = p.position from positions p where g.id = p.id;
select setval(pg_get_serial_sequence('public.workshare_groups','sort_order'),
  greatest((select max(sort_order) from public.workshare_groups), 1), true);
alter table public.workshare_groups add constraint workshare_groups_order_range
  check ((id = 'unassigned' and sort_order = 0) or (id <> 'unassigned' and sort_order > 0));
-- Deferred until the end of each statement so swapping positions is atomic.
alter table public.workshare_groups add constraint workshare_groups_order_unique
  unique(sort_order) deferrable initially immediate;
comment on column public.workshare_groups.sort_order is 'Canonical ascending display order across group lists. Unassigned is fixed at zero. New groups append; reorder via reorder_workshare_groups.';

create function public.reorder_workshare_groups(input jsonb) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare expected_count integer;
begin
  perform private.workshare_require_staff();
  if jsonb_typeof(input) is distinct from 'object'
    or input->>'action' is distinct from 'reorderGroups'
    or jsonb_typeof(input->'groups') is distinct from 'array' then
    raise check_violation using message = 'Provide the complete group order.';
  end if;
  -- Shares the existing group mutation lock. No account rows are changed.
  lock table public.workshare_groups in share row exclusive mode;
  select count(*) into expected_count from public.workshare_groups where id <> 'unassigned';
  if jsonb_array_length(input->'groups') <> expected_count then
    raise serialization_failure using message = 'Groups changed. Reload the roster before saving the order.';
  end if;
  if exists(select 1 from jsonb_array_elements(input->'groups') g
    where jsonb_typeof(g) is distinct from 'object'
      or jsonb_typeof(g->'id') is distinct from 'string'
      or jsonb_typeof(g->'updatedAt') is distinct from 'string')
    or (select count(distinct g->>'id') from jsonb_array_elements(input->'groups') g) <> expected_count then
    raise check_violation using message = 'Include every group exactly once.';
  end if;
  if exists(select 1 from jsonb_array_elements(input->'groups') item
    left join public.workshare_groups g on g.id = item->>'id' and g.id <> 'unassigned'
    where g.id is null or g.updated_at is distinct from (item->>'updatedAt')::timestamptz) then
    raise serialization_failure using message = 'Groups changed. Reload the roster before saving the order.';
  end if;
  update public.workshare_groups g set sort_order = ordered.position::integer
    from jsonb_array_elements(input->'groups') with ordinality ordered(item, position)
    where g.id = ordered.item->>'id' and g.sort_order <> ordered.position;
  return jsonb_build_object('success', true);
end;
$$;
revoke all on function public.reorder_workshare_groups(jsonb) from public, anon;
grant execute on function public.reorder_workshare_groups(jsonb) to authenticated, service_role;
notify pgrst, 'reload schema';
